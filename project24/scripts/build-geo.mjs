// Generates src/game/geo.generated.ts from Natural Earth 50m (world-atlas).
// Run: npm run geo  (only needed if you change the projection constants)
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topo, topo.objects.countries).features;

// Must match src/game/projection.ts
const LON0 = -10.2, LAT0 = 44.3, K = 80, COS = Math.cos((40 * Math.PI) / 180), PAD_X = 56, PAD_Y = 40;
const proj = ([lon, lat]) => [PAD_X + (lon - LON0) * K * COS, PAD_Y + (LAT0 - lat) * K];
const inView = ([x, y]) => x > -300 && x < 1300 && y > -300 && y < 1100;

function ringPath(ring) {
  const pts = ring.map(proj);
  if (!pts.some(inView)) return "";
  // light simplification: drop points closer than 1.2 units
  const out = [pts[0]];
  for (const p of pts.slice(1)) {
    const q = out[out.length - 1];
    if (Math.hypot(p[0] - q[0], p[1] - q[1]) > 1.2) out.push(p);
  }
  if (out.length < 4) return "";
  return "M" + out.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L") + "Z";
}
function polys(geom) {
  return geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
}
function area(ring) {
  let a = 0;
  for (let i = 0; i < ring.length - 1; i++) a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  return Math.abs(a / 2);
}
const byName = (n) => countries.find((c) => c.properties.name === n);

const spain = byName("Spain");
const sp = polys(spain.geometry).sort((a, b) => area(b[0]) - area(a[0]));
const mainland = ringPath(sp[0][0]);
const islands = sp.slice(1).map((p) => ringPath(p[0])).filter(Boolean).join("");

const neighbours = ["Portugal", "France", "Andorra", "Morocco", "Algeria", "Gibraltar"]
  .map(byName).filter(Boolean)
  .map((c) => polys(c.geometry).map((p) => ringPath(p[0])).join(""))
  .join("");

const out = `// AUTO-GENERATED by scripts/build-geo.mjs from Natural Earth (public domain). Do not edit.
export const SPAIN_MAINLAND = ${JSON.stringify(mainland)};
export const SPAIN_ISLANDS = ${JSON.stringify(islands)};
export const NEIGHBOURS = ${JSON.stringify(neighbours)};
`;
writeFileSync("src/game/geo.generated.ts", out);
console.log("ok", mainland.length, islands.length, neighbours.length);
